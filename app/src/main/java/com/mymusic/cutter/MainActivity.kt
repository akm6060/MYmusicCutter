package com.mymusic.cutter

import android.Manifest
import android.app.Activity
import android.content.Intent
import android.content.pm.ApplicationInfo
import android.content.pm.PackageManager
import android.graphics.Color
import android.graphics.Rect
import android.net.Uri
import android.os.Build
import android.os.Bundle
import android.os.SystemClock
import android.view.View
import android.view.ViewGroup
import android.view.WindowInsets
import android.view.WindowInsetsController
import android.view.WindowManager
import android.webkit.ValueCallback
import android.webkit.WebChromeClient
import android.webkit.WebResourceRequest
import android.webkit.WebResourceResponse
import android.webkit.WebView
import android.webkit.WebViewClient
import android.widget.FrameLayout
import android.widget.Toast
import android.view.TextureView
import androidx.media3.common.util.UnstableApi
import org.json.JSONObject

@UnstableApi
class MainActivity : Activity() {
    private lateinit var nativePlayer: NativePlayer
    private val pickRequestCode = 4110
    private lateinit var webView: WebView
    private lateinit var cutter: MYmusicNativeCutter
    private var fileChooserCallback: ValueCallback<Array<Uri>>? = null
    private val fileChooserRequestCode = 4107
    private val storagePermissionRequestCode = 4108
    private var lastBackAt = 0L
    private var pageReady = false
    private var pendingShared: String? = null
    private var pendingFileIntent: Intent? = null
    private val readPermissionRequestCode = 4109

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        requestedOrientation = android.content.pm.ActivityInfo.SCREEN_ORIENTATION_FULL_SENSOR

        webView = WebView(this)
        webView.layoutParams = FrameLayout.LayoutParams(
            ViewGroup.LayoutParams.MATCH_PARENT,
            ViewGroup.LayoutParams.MATCH_PARENT
        )
        // Transparent: the native video picture sits underneath the page's video area.
        webView.setBackgroundColor(Color.TRANSPARENT)
        webView.settings.javaScriptEnabled = true
        webView.settings.domStorageEnabled = true
        webView.settings.allowFileAccess = true
        webView.settings.allowContentAccess = true
        webView.settings.mediaPlaybackRequiresUserGesture = false

        // BuildConfig is not generated by default in Android Gradle Plugin 8+, so read the flag directly.
        val debuggable = (applicationInfo.flags and ApplicationInfo.FLAG_DEBUGGABLE) != 0
        WebView.setWebContentsDebuggingEnabled(debuggable)

        cutter = MYmusicNativeCutter(this, webView)
        webView.addJavascriptInterface(cutter, "MYmusicNativeCutter")
        val videoSurface = TextureView(this)
        videoSurface.layoutParams = FrameLayout.LayoutParams(1, 1)
        nativePlayer = NativePlayer(this, webView, cutter, videoSurface)
        webView.addJavascriptInterface(nativePlayer, "MYmusicNativePlayer")
        val root = FrameLayout(this)
        root.setBackgroundColor(Color.rgb(5, 6, 16))
        root.addView(videoSurface)
        root.addView(webView)

        webView.webChromeClient = object : WebChromeClient() {
            override fun onShowFileChooser(
                view: WebView?,
                filePathCallback: ValueCallback<Array<Uri>>?,
                fileChooserParams: FileChooserParams?
            ): Boolean {
                fileChooserCallback?.onReceiveValue(null)
                fileChooserCallback = filePathCallback
                return try {
                    val intent = fileChooserParams?.createIntent()
                        ?: Intent(Intent.ACTION_GET_CONTENT).apply {
                            addCategory(Intent.CATEGORY_OPENABLE)
                            type = "*/*"
                        }
                    if (fileChooserParams?.mode == FileChooserParams.MODE_OPEN_MULTIPLE) {
                        intent.putExtra(Intent.EXTRA_ALLOW_MULTIPLE, true)
                    }
                    startActivityForResult(intent, fileChooserRequestCode)
                    true
                } catch (_: Exception) {
                    fileChooserCallback?.onReceiveValue(null)
                    fileChooserCallback = null
                    false
                }
            }
        }
        webView.webViewClient = object : WebViewClient() {
            // Files received through "Open with" / "Share" are served to the page from here.
            // The page runs from https://appassets.androidplatform.net/assets/ (a local address served
            // from the APK), so the shared media below is same-origin: the equalizer, waveform and
            // thumbnails all work on it, and the player can seek (HTTP Range).
            override fun shouldInterceptRequest(view: WebView?, request: WebResourceRequest?): WebResourceResponse? {
                val url = request?.url ?: return null
                if (url.host != "appassets.androidplatform.net") return null
                val path = url.path ?: ""
                if (path.startsWith("/mymusic-shared/")) {
                    val range = request?.requestHeaders?.entries?.firstOrNull { it.key.equals("Range", ignoreCase = true) }?.value
                    return cutter.sharedResponse(url.lastPathSegment ?: "", range)
                }
                if (path.startsWith("/assets/")) {
                    val name = path.removePrefix("/assets/")
                    return try {
                        val mime = when (name.substringAfterLast('.', "").lowercase()) {
                            "html", "htm" -> "text/html"; "js" -> "application/javascript"; "css" -> "text/css"
                            "svg" -> "image/svg+xml"; "png" -> "image/png"; "json" -> "application/json"
                            else -> "application/octet-stream"
                        }
                        WebResourceResponse(mime, "utf-8", assets.open(name))
                    } catch (_: Exception) {
                        null
                    }
                }
                return null
            }

            override fun onPageFinished(view: WebView?, url: String?) {
                super.onPageFinished(view, url)
                pageReady = true
                pendingShared?.let { deliverShared(it) }
                pendingShared = null
            }

            override fun shouldOverrideUrlLoading(view: WebView?, request: WebResourceRequest?): Boolean {
                val url = request?.url?.toString() ?: return false
                return !url.startsWith("https://appassets.androidplatform.net/") &&
                       !url.startsWith("file:///android_asset/") &&
                       !url.startsWith("content:") &&
                       !url.startsWith("blob:")
            }
        }
        setContentView(root)
        cutter.clearSharedCache()
        webView.loadUrl("https://appassets.androidplatform.net/assets/index.html")
        handleIncoming(intent)

        // Android 9 and older need this to save into the public Movies/Music/Pictures folders.
        if (Build.VERSION.SDK_INT < 29 &&
            checkSelfPermission(Manifest.permission.WRITE_EXTERNAL_STORAGE) != PackageManager.PERMISSION_GRANTED
        ) {
            requestPermissions(arrayOf(Manifest.permission.WRITE_EXTERNAL_STORAGE), storagePermissionRequestCode)
        }
    }

    private var barsHidden = false

    override fun onWindowFocusChanged(hasFocus: Boolean) {
        super.onWindowFocusChanged(hasFocus)
        if (hasFocus && barsHidden) setFullscreenBars(true)
    }

    override fun onNewIntent(intent: Intent) {
        super.onNewIntent(intent)
        setIntent(intent)
        handleIncoming(intent)
    }

    /** Reads files sent by "Open with" (VIEW) or "Share" (SEND / SEND_MULTIPLE). */
    private fun handleIncoming(intent: Intent?) {
        if (intent == null) return
        val uris = ArrayList<Uri>()
        when (intent.action) {
            Intent.ACTION_VIEW -> intent.data?.let { uris.add(it) }
            Intent.ACTION_SEND -> {
                streamExtra(intent)?.let { uris.add(it) }
            }
            Intent.ACTION_SEND_MULTIPLE -> {
                streamListExtra(intent)?.let { uris.addAll(it) }
            }
        }
        if (uris.isEmpty()) {
            val clip = intent.clipData
            if (clip != null && intent.action != Intent.ACTION_MAIN) {
                for (i in 0 until clip.itemCount) clip.getItemAt(i).uri?.let { uris.add(it) }
            }
        }
        if (uris.isEmpty()) return
        val array = uris.distinct().toTypedArray()
        deliverUris(array, intent)
    }

    /** The app's own "Add" button: Android's file picker, files go straight to the native player. */
    fun pickMedia() {
        try {
            val i = Intent(Intent.ACTION_GET_CONTENT)
                .addCategory(Intent.CATEGORY_OPENABLE)
                .setType("*/*")
                .putExtra(Intent.EXTRA_MIME_TYPES, arrayOf("audio/*", "video/*", "application/ogg", "application/octet-stream"))
                .putExtra(Intent.EXTRA_ALLOW_MULTIPLE, true)
            @Suppress("DEPRECATION")
            startActivityForResult(Intent.createChooser(i, "Choose audio or video"), pickRequestCode)
        } catch (_: Exception) {
            Toast.makeText(this, "No file picker found", Toast.LENGTH_LONG).show()
        }
    }

    private fun deliverUris(array: Array<Uri>, intent: Intent?) {
        // Old file managers send file:// paths; reading those needs the storage permission (Android 12 and older).
        if (Build.VERSION.SDK_INT in 23..32 && array.any { it.scheme == "file" } &&
            checkSelfPermission(Manifest.permission.READ_EXTERNAL_STORAGE) != PackageManager.PERMISSION_GRANTED
        ) {
            pendingFileIntent = intent ?: Intent(Intent.ACTION_SEND_MULTIPLE).putParcelableArrayListExtra(Intent.EXTRA_STREAM, ArrayList(array.toList()))
            requestPermissions(arrayOf(Manifest.permission.READ_EXTERNAL_STORAGE), readPermissionRequestCode)
            return
        }
        // Preparing can take a while (protected files are copied once), so it runs off the screen thread.
        Thread {
            val json = cutter.registerShared(array) { name, pct ->
                val n = JSONObject.quote(name)
                runOnUiThread {
                    if (pageReady) webView.evaluateJavascript("window.__mymusicPreparing&&window.__mymusicPreparing($n,$pct)", null)
                }
            }
            runOnUiThread { if (pageReady) deliverShared(json) else pendingShared = json }
        }.start()
    }

    override fun onRequestPermissionsResult(requestCode: Int, permissions: Array<out String>, grantResults: IntArray) {
        super.onRequestPermissionsResult(requestCode, permissions, grantResults)
        if (requestCode != readPermissionRequestCode) return
        val waiting = pendingFileIntent
        pendingFileIntent = null
        if (waiting != null && grantResults.isNotEmpty() && grantResults[0] == PackageManager.PERMISSION_GRANTED) {
            handleIncoming(waiting)
        } else if (waiting != null) {
            Toast.makeText(this, "Storage permission is needed to open this file", Toast.LENGTH_LONG).show()
        }
    }

    @Suppress("DEPRECATION")
    private fun streamExtra(intent: Intent): Uri? =
        if (Build.VERSION.SDK_INT >= 33) intent.getParcelableExtra(Intent.EXTRA_STREAM, Uri::class.java)
        else intent.getParcelableExtra<Uri>(Intent.EXTRA_STREAM)

    @Suppress("DEPRECATION")
    private fun streamListExtra(intent: Intent): List<Uri>? =
        if (Build.VERSION.SDK_INT >= 33) intent.getParcelableArrayListExtra(Intent.EXTRA_STREAM, Uri::class.java)
        else intent.getParcelableArrayListExtra<Uri>(Intent.EXTRA_STREAM)

    private fun deliverShared(json: String) {
        webView.evaluateJavascript("window.__mymusicOpenShared&&window.__mymusicOpenShared($json)", null)
    }

    /** Hide or show the status and navigation bars (used by fullscreen video). */
    // Named differently from Activity.setImmersive(), which means something else.
    fun setFullscreenBars(on: Boolean) {
        barsHidden = on
        // 100% of the screen: the picture also goes under the camera cut-out, and the screen stays awake.
        if (Build.VERSION.SDK_INT >= 28) {
            val attrs = window.attributes
            attrs.layoutInDisplayCutoutMode = when {
                !on -> WindowManager.LayoutParams.LAYOUT_IN_DISPLAY_CUTOUT_MODE_DEFAULT
                Build.VERSION.SDK_INT >= 30 -> WindowManager.LayoutParams.LAYOUT_IN_DISPLAY_CUTOUT_MODE_ALWAYS
                else -> WindowManager.LayoutParams.LAYOUT_IN_DISPLAY_CUTOUT_MODE_SHORT_EDGES
            }
            window.attributes = attrs
        }
        if (on) {
            window.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
            window.addFlags(WindowManager.LayoutParams.FLAG_FULLSCREEN)
        } else {
            window.clearFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
            window.clearFlags(WindowManager.LayoutParams.FLAG_FULLSCREEN)
        }
        if (Build.VERSION.SDK_INT >= 21) {
            window.statusBarColor = Color.BLACK
            window.navigationBarColor = Color.BLACK
        }
        if (Build.VERSION.SDK_INT >= 30) {
            window.setDecorFitsSystemWindows(!on)
            val controller = window.insetsController ?: return
            if (on) {
                controller.systemBarsBehavior = WindowInsetsController.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE
                controller.hide(WindowInsets.Type.systemBars())
            } else {
                controller.show(WindowInsets.Type.systemBars())
            }
        } else {
            setLegacySystemUi(on)
        }
    }

    @Suppress("DEPRECATION")
    private fun setLegacySystemUi(on: Boolean) {
        window.decorView.systemUiVisibility = if (on) {
                View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY or
                    View.SYSTEM_UI_FLAG_FULLSCREEN or
                    View.SYSTEM_UI_FLAG_HIDE_NAVIGATION or
                    View.SYSTEM_UI_FLAG_LAYOUT_STABLE or
                    View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN or
                    View.SYSTEM_UI_FLAG_LAYOUT_HIDE_NAVIGATION
            } else {
                View.SYSTEM_UI_FLAG_VISIBLE
            }
    }

    @Deprecated("Deprecated in Android, retained for compatibility with WebView file chooser")
    override fun onActivityResult(requestCode: Int, resultCode: Int, data: Intent?) {
        super.onActivityResult(requestCode, resultCode, data)
        if (requestCode == pickRequestCode) {
            if (resultCode == RESULT_OK && data != null) {
                val clip = data.clipData
                val picked = if (clip != null && clip.itemCount > 0) (0 until clip.itemCount).mapNotNull { clip.getItemAt(it).uri }
                             else listOfNotNull(data.data)
                if (picked.isNotEmpty()) deliverUris(picked.distinct().toTypedArray(), null)
            }
            return
        }
        if (requestCode != fileChooserRequestCode) return
        val callback = fileChooserCallback ?: return
        fileChooserCallback = null

        // WebView's own parser only returns a single file, so multi-select is read from ClipData here.
        var results: Array<Uri>? = null
        if (resultCode == RESULT_OK && data != null) {
            val clip = data.clipData
            results = if (clip != null && clip.itemCount > 0) {
                (0 until clip.itemCount).mapNotNull { clip.getItemAt(it).uri }.toTypedArray()
            } else {
                data.data?.let { arrayOf(it) }
            }
            if (results != null && results.isEmpty()) results = null
        }
        results?.let { cutter.rememberPicked(it) }
        callback.onReceiveValue(results)
    }

    /** Called from JavaScript: areas where an edge swipe must not count as Back (the cutter timeline). */
    fun setGestureExclusion(rects: List<Rect>) {
        if (Build.VERSION.SDK_INT >= 29 && ::webView.isInitialized) {
            webView.setSystemGestureExclusionRects(rects)
        }
    }

    // Back (button or edge swipe): first closes the equalizer or leaves fullscreen.
    // On the main screen it asks once more, then stops playback and closes the app.
    @Suppress("DEPRECATION")
    @Deprecated("Deprecated in Android, retained for compatibility")
    override fun onBackPressed() {
        if (!::webView.isInitialized) {
            super.onBackPressed()
            return
        }
        webView.evaluateJavascript(
            "(window.__mymusicHandleBack&&window.__mymusicHandleBack())?'1':'0'"
        ) { result ->
            if (result == "\"1\"") return@evaluateJavascript
            val now = SystemClock.elapsedRealtime()
            if (now - lastBackAt < 2000) {
                pausePlayback()
                finish()
            } else {
                lastBackAt = now
                Toast.makeText(this, "Go back again to exit", Toast.LENGTH_SHORT).show()
            }
        }
    }

    private fun pausePlayback() {
        if (::webView.isInitialized) {
            webView.evaluateJavascript("window.__mymusicPauseAll&&window.__mymusicPauseAll()", null)
        }
    }

    // Nothing keeps playing once the app leaves the screen (Home, app switch, screen off).
    override fun onPause() {
        pausePlayback()
        if (::nativePlayer.isInitialized) nativePlayer.pauseFromActivity()
        super.onPause()
    }

    override fun onDestroy() {
        fileChooserCallback?.onReceiveValue(null)
        fileChooserCallback = null
        if (::nativePlayer.isInitialized) nativePlayer.release()
        if (::cutter.isInitialized) {
            cutter.shutdown()
            if (isFinishing) cutter.clearSharedCache()
        }
        if (::webView.isInitialized) {
            (webView.parent as? ViewGroup)?.removeView(webView)
            webView.stopLoading()
            webView.destroy()
        }
        super.onDestroy()
    }
}
