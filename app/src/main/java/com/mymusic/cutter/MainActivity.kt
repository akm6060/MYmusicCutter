            override fun close() {
                runOnUiThread {
                    if (::nativePlayer.isInitialized) nativePlayer.pauseFromActivity()
                    pausePlayback()
                }
            }
            override fun exit() {
                runOnUiThread {
                    if (::nativePlayer.isInitialized) nativePlayer.pauseFromActivity()
                    pausePlayback()
