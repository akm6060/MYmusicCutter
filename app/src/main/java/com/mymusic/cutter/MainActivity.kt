            }
        }

        webView.webChromeClient = object : WebChromeClient() {
            override fun onShowFileChooser(
                view: WebView?,
                filePathCallback: ValueCallback<Array<Uri>>?,
                fileChooserParams: FileChooserParams?
            ): Boolean {
                fileChooserCallback?.onReceiveValue(null)
                fileChooserCallback = filePathCallback
                return try {
                    val intent = fileChooserParams?.createIntent()
                        ?: Intent(Intent.ACTION_GET_CONTENT).apply {
                            addCategory(Intent.CATEGORY_OPENABLE)
                            type = "*/*"
                        }
                    if (fileChooserParams?.mode == FileChooserParams.MODE_OPEN_MULTIPLE) {
                        intent.putExtra(Intent.EXTRA_ALLOW_MULTIPLE, true)
                    }
                    startActivityForResult(intent, fileChooserRequestCode)
                    true
                } catch (_: Exception) {
                    fileChooserCallback?.onReceiveValue(null)
                    fileChooserCallback = null
                    false
                }
            }
        }
        webView.webViewClient = object : WebViewClient() {
            // Files received through "Open with" / "Share" are served to the page from here.
            // The page runs from https://appassets.androidplatform.net/assets/ (a local address served
            // from the APK), so the shared media below is same-origin: the equalizer, waveform and
            // thumbnails all work on it, and the player can seek (HTTP Range).
            override fun shouldInterceptRequest(view: WebView?, request: WebResourceRequest?): WebResourceResponse? {
                val url = request?.url ?: return null
                if (url.host != "appassets.androidplatform.net") return null
                val path = url.path ?: ""
                if (path.startsWith("/mymusic-shared/")) {
                    val range = request?.requestHeaders?.entries?.firstOrNull { it.key.equals("Range", ignoreCase = true) }?.value
                    return cutter.sharedResponse(url.lastPathSegment ?: "", range)
                }
                if (path.startsWith("/assets/")) {
                    val name = path.removePrefix("/assets/")
                    return try {
                        val mime = when (name.substringAfterLast('.', "").lowercase()) {
                            "html", "htm" -> "text/html"; "js" -> "application/javascript"; "css" -> "text/css"
                            "svg" -> "image/svg+xml"; "png" -> "image/png"; "json" -> "application/json"
                            else -> "application/octet-stream"
                        }
                        WebResourceResponse(mime, "utf-8", assets.open(name))
                    } catch (_: Exception) {
                        null
                    }
                }
                return null
            }

            override fun onPageFinished(view: WebView?, url: String?) {
                super.onPageFinished(view, url)
                pageReady = true
                pendingShared?.let { deliverShared(it) }
                pendingShared = null
            }

            override fun shouldOverrideUrlLoading(view: WebView?, request: WebResourceRequest?): Boolean {
                val url = request?.url?.toString() ?: return false
                return !url.startsWith("https://appassets.androidplatform.net/") &&
                       !url.startsWith("file:///android_asset/") &&
                       !url.startsWith("content:") &&
                       !url.startsWith("blob:")
            }
        }
        setContentView(root)
        cutter.clearSharedCache()
        webView.loadUrl("https://appassets.androidplatform.net/assets/index.html")
        handleIncoming(intent)

        // Android 9 and older need this to save into the public Movies/Music/Pictures folders.
        if (Build.VERSION.SDK_INT < 29 &&
            checkSelfPermission(Manifest.permission.WRITE_EXTERNAL_STORAGE) != PackageManager.PERMISSION_GRANTED
        ) {
            requestPermissions(arrayOf(Manifest.permission.WRITE_EXTERNAL_STORAGE), storagePermissionRequestCode)
        }
    }

    private var barsHidden = false

    override fun onWindowFocusChanged(hasFocus: Boolean) {
        super.onWindowFocusChanged(hasFocus)
        if (hasFocus && barsHidden) setFullscreenBars(true)
    }

    override fun onNewIntent(intent: Intent) {
        super.onNewIntent(intent)
        setIntent(intent)
        handleIncoming(intent)
    }

    /** Reads files sent by "Open with" (VIEW) or "Share" (SEND / SEND_MULTIPLE). */
    private fun handleIncoming(intent: Intent?) {
        if (intent == null) return
        val uris = ArrayList<Uri>()
        when (intent.action) {
            Intent.ACTION_VIEW -> intent.data?.let { uris.add(it) }
            Intent.ACTION_SEND -> {
                streamExtra(intent)?.let { uris.add(it) }
            }
            Intent.ACTION_SEND_MULTIPLE -> {
                streamListExtra(intent)?.let { uris.addAll(it) }
            }
        }
        if (uris.isEmpty()) {
            val clip = intent.clipData
            if (clip != null && intent.action != Intent.ACTION_MAIN) {
                for (i in 0 until clip.itemCount) clip.getItemAt(i).uri?.let { uris.add(it) }
            }
        }
        if (uris.isEmpty()) return
        val array = uris.distinct().toTypedArray()
        deliverUris(array, intent)
    }

    /** The app's own "Add" button: Android's file picker, files go straight to the native player. */
    fun pickMedia() {
        try {
            val i = Intent(Intent.ACTION_GET_CONTENT)
                .addCategory(Intent.CATEGORY_OPENABLE)
                .setType("*/*")
                .putExtra(Intent.EXTRA_MIME_TYPES, arrayOf("audio/*", "video/*", "application/ogg", "application/octet-stream"))
                .putExtra(Intent.EXTRA_ALLOW_MULTIPLE, true)
            @Suppress("DEPRECATION")
            startActivityForResult(Intent.createChooser(i, "Choose audio or video"), pickRequestCode)
        } catch (_: Exception) {
            Toast.makeText(this, "No file picker found", Toast.LENGTH_LONG).show()
        }
    }

    private fun mediaPermissions(): Array<String> =
        if (Build.VERSION.SDK_INT >= 33) arrayOf("android.permission.READ_MEDIA_AUDIO", "android.permission.READ_MEDIA_VIDEO")
        else arrayOf(Manifest.permission.READ_EXTERNAL_STORAGE)

    /** The file manager needs permission to read music and videos on the phone. */
    fun hasMediaPermission(): Boolean = mediaPermissions().all { checkSelfPermission(it) == PackageManager.PERMISSION_GRANTED }

    fun requestMediaPermission() {
        if (hasMediaPermission()) { tellFilePermission(true); return }
        requestPermissions(mediaPermissions(), mediaPermissionCode)
    }

    private fun tellFilePermission(granted: Boolean) {
        if (pageReady) webView.evaluateJavascript("window.__fmPermission&&window.__fmPermission(${if (granted) "true" else "false"})", null)
    }

    /** Light theme: pale window and dark status-bar icons; dark theme: the reverse. */
    fun applyTheme(light: Boolean) {
        rootView?.setBackgroundColor(if (light) Color.rgb(244, 245, 251) else Color.rgb(5, 6, 16))
        if (Build.VERSION.SDK_INT >= 30) {
            val c = window.insetsController
            val flags = WindowInsetsController.APPEARANCE_LIGHT_STATUS_BARS or WindowInsetsController.APPEARANCE_LIGHT_NAVIGATION_BARS
            c?.setSystemBarsAppearance(if (light && !barsHidden) flags else 0, flags)
        } else if (!barsHidden) {
            @Suppress("DEPRECATION")
            window.decorView.systemUiVisibility = if (light) View.SYSTEM_UI_FLAG_LIGHT_STATUS_BAR else View.SYSTEM_UI_FLAG_VISIBLE
        }
    }

    fun pickFolder() {
