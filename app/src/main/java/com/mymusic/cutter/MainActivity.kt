    fun openUriFromList(uriText: String) {
        val uri = try { Uri.parse(uriText) } catch (_: Exception) { null } ?: return
        deliverUris(arrayOf(uri), null)
    }

    private val mediaExt = setOf("mp4", "m4v", "mkv", "webm", "3gp", "mov", "avi", "ts", "m2ts", "mts", "flv", "wmv", "mpg", "mpeg",
        "mp3", "m4a", "m4b", "aac", "wav", "flac", "ogg", "oga", "opus", "amr", "wma", "aiff", "aif", "mka")

    /** Lists the audio and video files of a chosen folder (sorted by name) and sends them to the page. */
    private fun listFolder(tree: Uri) {
        try {
            contentResolver.takePersistableUriPermission(tree, Intent.FLAG_GRANT_READ_URI_PERMISSION)
        } catch (_: Exception) {}
        Thread {
            val arr = org.json.JSONArray()
            try {
                val docId = android.provider.DocumentsContract.getTreeDocumentId(tree)
                val children = android.provider.DocumentsContract.buildChildDocumentsUriUsingTree(tree, docId)
                val cols = arrayOf(
                    android.provider.DocumentsContract.Document.COLUMN_DOCUMENT_ID,
                    android.provider.DocumentsContract.Document.COLUMN_DISPLAY_NAME,
                    android.provider.DocumentsContract.Document.COLUMN_MIME_TYPE,
                    android.provider.DocumentsContract.Document.COLUMN_SIZE
                )
                val rows = ArrayList<Array<Any>>()
                contentResolver.query(children, cols, null, null, null)?.use { c ->
                    while (c.moveToNext()) {
                        val id = c.getString(0) ?: continue
                        val name = c.getString(1) ?: continue
                        val mime = c.getString(2) ?: ""
                        val size = if (c.isNull(3)) -1L else c.getLong(3)
                        val ext = name.substringAfterLast('.', "").lowercase()
                        if (mime.startsWith("audio/") || mime.startsWith("video/") || ext in mediaExt) {
                            rows.add(arrayOf<Any>(id, name, mime, size))
                        }
                    }
                }
                rows.sortWith { a, b -> naturalCompare(a[1] as String, b[1] as String) }
                for (r in rows) {
                    val u = android.provider.DocumentsContract.buildDocumentUriUsingTree(tree, r[0] as String)
                    arr.put(JSONObject().put("uri", u.toString()).put("name", r[1]).put("type", r[2]).put("size", r[3]))
                }
            } catch (e: Exception) {
                runOnUiThread { Toast.makeText(this, "This folder could not be read", Toast.LENGTH_LONG).show() }
            }
            val json = arr.toString()
            runOnUiThread { if (pageReady) webView.evaluateJavascript("window.__mmFolder&&window.__mmFolder($json)", null) }
        }.start()
    }

    /** "Song 2" before "Song 10". */
    private fun naturalCompare(a: String, b: String): Int {
        val ra = Regex("(\\d+)|(\\D+)").findAll(a.lowercase()).map { it.value }.toList()
        val rb = Regex("(\\d+)|(\\D+)").findAll(b.lowercase()).map { it.value }.toList()
        for (i in 0 until minOf(ra.size, rb.size)) {
            val x = ra[i]; val y = rb[i]
            val c = if (x[0].isDigit() && y[0].isDigit()) (x.toBigInteger().compareTo(y.toBigInteger())) else x.compareTo(y)
            if (c != 0) return c
        }
        return ra.size - rb.size
    }

    private fun deliverUris(array: Array<Uri>, intent: Intent?) {
        // Old file managers send file:// paths; reading those needs the storage permission (Android 12 and older).
        val readPerms = if (Build.VERSION.SDK_INT >= 33) arrayOf("android.permission.READ_MEDIA_VIDEO", "android.permission.READ_MEDIA_AUDIO")
                        else arrayOf(Manifest.permission.READ_EXTERNAL_STORAGE)
        if (array.any { it.scheme == "file" } && readPerms.any { checkSelfPermission(it) != PackageManager.PERMISSION_GRANTED }) {
            pendingFileIntent = intent ?: Intent(Intent.ACTION_SEND_MULTIPLE).putParcelableArrayListExtra(Intent.EXTRA_STREAM, ArrayList(array.toList()))
            requestPermissions(readPerms, readPermissionRequestCode)
            return
        }
        // Preparing can take a while (protected files are copied once), so it runs off the screen thread.
        Thread {
            val json = cutter.registerShared(array) { name, pct ->
                val n = JSONObject.quote(name)
                runOnUiThread {
                    if (pageReady) webView.evaluateJavascript("window.__mymusicPreparing&&window.__mymusicPreparing($n,$pct)", null)
                }
            }
            runOnUiThread { if (pageReady) deliverShared(json) else pendingShared = json }
        }.start()
    }

    override fun onRequestPermissionsResult(requestCode: Int, permissions: Array<out String>, grantResults: IntArray) {
        super.onRequestPermissionsResult(requestCode, permissions, grantResults)
        if (requestCode == mediaPermissionCode) {
            tellFilePermission(grantResults.isNotEmpty() && grantResults.all { it == PackageManager.PERMISSION_GRANTED })
            return
        }
        if (requestCode != readPermissionRequestCode) return
        val waiting = pendingFileIntent
        pendingFileIntent = null
        if (waiting != null && grantResults.isNotEmpty() && grantResults.any { it == PackageManager.PERMISSION_GRANTED }) {
            handleIncoming(waiting)
        } else if (waiting != null) {
            Toast.makeText(this, "Storage permission is needed to open this file", Toast.LENGTH_LONG).show()
        }
    }

    @Suppress("DEPRECATION")
    private fun streamExtra(intent: Intent): Uri? =
        if (Build.VERSION.SDK_INT >= 33) intent.getParcelableExtra(Intent.EXTRA_STREAM, Uri::class.java)
        else intent.getParcelableExtra<Uri>(Intent.EXTRA_STREAM)

    @Suppress("DEPRECATION")
    private fun streamListExtra(intent: Intent): List<Uri>? =
        if (Build.VERSION.SDK_INT >= 33) intent.getParcelableArrayListExtra(Intent.EXTRA_STREAM, Uri::class.java)
        else intent.getParcelableArrayListExtra<Uri>(Intent.EXTRA_STREAM)

    private fun deliverShared(json: String) {
        webView.evaluateJavascript("window.__mymusicOpenShared&&window.__mymusicOpenShared($json)", null)
    }

    /** Hide or show the status and navigation bars (used by fullscreen video). */
    // Named differently from Activity.setImmersive(), which means something else.
    fun setFullscreenBars(on: Boolean) {
        barsHidden = on
        rootView?.requestApplyInsets()
        // 100% of the screen: the picture also goes under the camera cut-out, and the screen stays awake.
        if (Build.VERSION.SDK_INT >= 28) {
            val attrs = window.attributes
            attrs.layoutInDisplayCutoutMode = when {
                !on -> WindowManager.LayoutParams.LAYOUT_IN_DISPLAY_CUTOUT_MODE_DEFAULT
                Build.VERSION.SDK_INT >= 30 -> WindowManager.LayoutParams.LAYOUT_IN_DISPLAY_CUTOUT_MODE_ALWAYS
                else -> WindowManager.LayoutParams.LAYOUT_IN_DISPLAY_CUTOUT_MODE_SHORT_EDGES
            }
            window.attributes = attrs
        }
        if (on) {
            window.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
            window.addFlags(WindowManager.LayoutParams.FLAG_FULLSCREEN)
        } else {
            window.clearFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
            window.clearFlags(WindowManager.LayoutParams.FLAG_FULLSCREEN)
        }
        if (Build.VERSION.SDK_INT >= 21) {
            window.statusBarColor = Color.BLACK
            window.navigationBarColor = Color.BLACK
        }
        if (Build.VERSION.SDK_INT >= 30) {
            window.setDecorFitsSystemWindows(!on)
            val controller = window.insetsController ?: return
            if (on) {
                controller.systemBarsBehavior = WindowInsetsController.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE
                controller.hide(WindowInsets.Type.systemBars())
            } else {
                controller.show(WindowInsets.Type.systemBars())
            }
        } else {
            setLegacySystemUi(on)
        }
    }

    @Suppress("DEPRECATION")
    private fun setLegacySystemUi(on: Boolean) {
        window.decorView.systemUiVisibility = if (on) {
                View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY or
                    View.SYSTEM_UI_FLAG_FULLSCREEN or
                    View.SYSTEM_UI_FLAG_HIDE_NAVIGATION or
                    View.SYSTEM_UI_FLAG_LAYOUT_STABLE or
                    View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN or
                    View.SYSTEM_UI_FLAG_LAYOUT_HIDE_NAVIGATION
            } else {
                View.SYSTEM_UI_FLAG_VISIBLE
            }
    }

    @Deprecated("Deprecated in Android, retained for compatibility with WebView file chooser")
    override fun onActivityResult(requestCode: Int, resultCode: Int, data: Intent?) {
        super.onActivityResult(requestCode, resultCode, data)
        if (requestCode == folderRequestCode) {
            val tree = data?.data
            if (resultCode == RESULT_OK && tree != null) listFolder(tree)
            return
        }
        if (requestCode == pickRequestCode) {
            if (resultCode == RESULT_OK && data != null) {
                val clip = data.clipData
                val picked = if (clip != null && clip.itemCount > 0) (0 until clip.itemCount).mapNotNull { clip.getItemAt(it).uri }
                             else listOfNotNull(data.data)
                if (picked.isNotEmpty()) deliverUris(picked.distinct().toTypedArray(), null)
            }
            return
        }
        if (requestCode != fileChooserRequestCode) return
        val callback = fileChooserCallback ?: return
        fileChooserCallback = null

        // WebView's own parser only returns a single file, so multi-select is read from ClipData here.
        var results: Array<Uri>? = null
        if (resultCode == RESULT_OK && data != null) {
            val clip = data.clipData
            results = if (clip != null && clip.itemCount > 0) {
                (0 until clip.itemCount).mapNotNull { clip.getItemAt(it).uri }.toTypedArray()
            } else {
                data.data?.let { arrayOf(it) }
            }
            if (results != null && results.isEmpty()) results = null
        }
        results?.let { cutter.rememberPicked(it) }
        callback.onReceiveValue(results)
    }

    /** Called from JavaScript: areas where an edge swipe must not count as Back (the cutter timeline). */
    fun setGestureExclusion(rects: List<Rect>) {
        if (Build.VERSION.SDK_INT >= 29 && ::webView.isInitialized) {
            webView.setSystemGestureExclusionRects(rects)
        }
    }

    // Back (button or edge swipe): first closes the equalizer or leaves fullscreen.
    // On the main screen it asks once more, then stops playback and closes the app.
    @Suppress("DEPRECATION")
    @Deprecated("Deprecated in Android, retained for compatibility")
    override fun onBackPressed() {
        if (!::webView.isInitialized) {
            super.onBackPressed()
            return
        }
        webView.evaluateJavascript(
            "(window.__mymusicHandleBack&&window.__mymusicHandleBack())?'1':'0'"
        ) { result ->
            if (result == "\"1\"") return@evaluateJavascript
            val now = SystemClock.elapsedRealtime()
            if (now - lastBackAt < 2000) {
                pausePlayback()
                finish()
            } else {
                lastBackAt = now
                Toast.makeText(this, "Go back again to exit", Toast.LENGTH_SHORT).show()
            }
        }
    }

    private fun pausePlayback() {
        if (::webView.isInitialized) {
            webView.evaluateJavascript("window.__mymusicPauseAll&&window.__mymusicPauseAll()", null)
        }
    }

    // Sound keeps playing in the background (Home, app switch, screen off);
    // the notification has Play / Pause and Close.
    override fun onPause() {
        super.onPause()
    }

    private var notifAsked = false
    fun askNotificationsOnce() {
        if (notifAsked || Build.VERSION.SDK_INT < 33) return
        notifAsked = true
        val prefs = getSharedPreferences("mm", MODE_PRIVATE)
        if (prefs.getBoolean("notifAsked", false)) return
        if (checkSelfPermission(Manifest.permission.POST_NOTIFICATIONS) == PackageManager.PERMISSION_GRANTED) return
        prefs.edit().putBoolean("notifAsked", true).apply()
        runOnUiThread { try { requestPermissions(arrayOf(Manifest.permission.POST_NOTIFICATIONS), 7301) } catch (_: Exception) {} }
    }

    override fun onDestroy() {
        fileChooserCallback?.onReceiveValue(null)
        fileChooserCallback = null
        PlaybackService.control = null
        PlaybackService.stop(this)
        if (::nativePlayer.isInitialized) nativePlayer.release()
        if (::cutter.isInitialized) {
            cutter.shutdown()
            if (isFinishing) cutter.clearSharedCache()
        }
        if (::webView.isInitialized) {
            (webView.parent as? ViewGroup)?.removeView(webView)
            webView.stopLoading()
            webView.destroy()
        }
        super.onDestroy()
    }
